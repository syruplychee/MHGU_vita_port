"""Inputs for offline, host-only locked-binary reference tests."""
import argparse
from pathlib import Path


def inputs(kind):
    parser = argparse.ArgumentParser(description=f"Compare the {kind} C fixtures with locked A32 instructions")
    parser.add_argument("--image", type=Path, required=True, help="Decoded, unrelocated locked main image")
    parser.add_argument("--fixtures", type=Path, required=True, help="Directory generated by the matching fixture executable")
    args = parser.parse_args()
    return args.fixtures, args.image.read_bytes(), Path(__file__).resolve().parents[3]
